"""Build the unified (T, N) tables for all three datasets -> data/<ds>/{texts,pairs}.parquet + data/DATA_REPORT.md"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import pandas as pd  # noqa: E402
from dv.data import BUILDERS  # noqa: E402

lines = ["# Data report (generated by scripts/01_build_datasets.py)\n"]
for name, build in BUILDERS.items():
    texts, pairs = build()
    out = ROOT / "data" / name
    out.mkdir(parents=True, exist_ok=True)
    assert texts.uid.is_unique
    texts.to_parquet(out / "texts.parquet")
    pairs.to_parquet(out / "pairs.parquet")
    lines.append(f"## {name}\n\ntexts: {len(texts)}\n")
    for sp, g in texts.groupby("split"):
        v = g.dropna(subset=["T", "N"])
        ct = pd.crosstab(v["T"], v["N"])
        agree = (v["T"] == v["N"]).mean() if len(v) else float("nan")
        lines.append(f"- **{sp}**: n={len(g)}, both-labelled={len(v)}, P(T==N)={agree:.3f}, cells (rows T, cols N)={ct.values.tolist()}")
    lines.append(f"\npairs: {pairs.groupby('kind').size().to_dict()}\n")
    ex = pairs[pairs.kind == "nuisance"].head(2)
    tx = texts.set_index("uid").text
    for _, p in ex.iterrows():
        lines.append(f"> A: {tx[p.uid_a][:300]}\n>\n> B: {tx[p.uid_b][:300]}\n")
    print("\n".join(lines[-12:]))
(ROOT / "data" / "DATA_REPORT.md").write_text("\n".join(lines))
